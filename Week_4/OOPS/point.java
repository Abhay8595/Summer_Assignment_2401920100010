public class point
{
    private int x;
    private int y;
    public point(int x, int y)
    {
        this.x = x;
        this.y = y;
    }

    public point(){

    }

    public void setX(int x) {
        this.x = x;
    }

    public void setY(int y) {
        this.y = y;
    }
    public void setXY(int x, int y) {
        this.x = x;
        this.y = y;
    }
}
